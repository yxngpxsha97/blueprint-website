export function getFleetT(language: FleetLanguage) {
  return (key: string): string => {
    return translations[language]?.[key] ?? translations['EN']?.[key] ?? key;
  };
}

export function useFleetLanguage() {
  const [language, setLanguage] = useState<FleetLanguage>('EN');

  useEffect(() => {
    try {
      const saved = localStorage.getItem('fleet_language') as FleetLanguage | null;
      if (saved === 'NL' || saved === 'EN' || saved === 'DE') setLanguage(saved);
    } catch { /* ignore */ }

    const handler = (e: Event) => {
      const lang = (e as CustomEvent<{ language: FleetLanguage }>).detail.language;
      if (lang === 'NL' || lang === 'EN' || lang === 'DE') setLanguage(lang);
    };
    window.addEventListener('fleet-language-change', handler);
    return () => window.removeEventListener('fleet-language-change', handler);
  }, []);

  return { language, t: getFleetT(language) };
}
