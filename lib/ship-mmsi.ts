/**
 * Returns MMSI strings for a set of ships.
 * Only ships with a real MMSI in cruise-ships.ts or STATIC_MMSI_MAP are included.
 * Ships without a known MMSI are omitted — use bounding box filtering instead.
 */
export function getMMSIsForShips(ships: CruiseShip[]): string[] {
  const mmsis: string[] = [];

  for (const ship of ships) {
    // Prefer MMSI already in the database record
    if (ship.mmsi && ship.mmsi.trim() !== '') {
      mmsis.push(ship.mmsi.trim());
      continue;
    }
    // Fall back to static map
    const mapped = STATIC_MMSI_MAP[ship.imo];
    if (mapped) {
      mmsis.push(mapped);
    }
  }

  return [...new Set(mmsis)]; // deduplicate
}

/**
 * Build a Map from MMSI → CruiseShip for fast AIS message lookups.
 */
export function buildMmsiIndex(ships: CruiseShip[]): Map<string, CruiseShip> {
  const index = new Map<string, CruiseShip>();

  for (const ship of ships) {
    if (ship.mmsi && ship.mmsi.trim() !== '') {
      index.set(ship.mmsi.trim(), ship);
    }
    const mapped = STATIC_MMSI_MAP[ship.imo];
    if (mapped) {
      index.set(mapped, ship);
    }
  }

  return index;
}
